'use strict';
const assert = require('node:assert/strict');
const { validarCif, validarDni, validarNie, validarNif, tipoNif, tipoEntidad } = require('./index.js');

assert.equal(validarCif('A46103834'), true);
assert.equal(validarCif('a-46.103.834'), true);
assert.equal(validarCif('Q2826000H'), true);
assert.equal(validarCif('A46103835'), false);
assert.equal(validarCif('Q2826000I'), false);
assert.equal(validarCif('B1234567'), false);
assert.equal(validarCif('12345678Z'), false);
assert.equal(validarCif(''), false);
assert.equal(validarCif(null), false);
assert.equal(validarDni('12345678Z'), true);
assert.equal(validarDni('12345678A'), false);
assert.equal(validarNie('X1234567L'), true);
assert.equal(validarNie('Y1234567X'), true);
assert.equal(validarNie('Z1234567R'), true);
assert.equal(validarNie('X1234567A'), false);
assert.equal(validarNif('A46103834'), true);
assert.equal(validarNif('12345678Z'), true);
assert.equal(validarNif('X1234567L'), true);
assert.equal(validarNif('ZZZ'), false);
assert.equal(tipoNif('A46103834'), 'cif');
assert.equal(tipoNif('12345678Z'), 'dni');
assert.equal(tipoNif('X1234567L'), 'nie');
assert.equal(tipoNif('A46103835'), null);
assert.equal(tipoEntidad('B00000000'), 'Sociedad de responsabilidad limitada');
assert.equal(tipoEntidad('A46103835'), null);
console.log('OK');
